-- 公告、站内通知、审计、配置与媒体；不生成任何演示业务数据。
CREATE TABLE xl_announcement (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '公告主键',
    title VARCHAR(60) NOT NULL COMMENT '公告标题',
    body VARCHAR(1200) NOT NULL COMMENT '公告正文',
    category VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '公告分类',
    scope VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '展示范围',
    status VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'draft' COMMENT '草稿、发布或撤回',
    created_by BIGINT UNSIGNED NOT NULL COMMENT '创建管理员',
    updated_by BIGINT UNSIGNED NOT NULL COMMENT '更新管理员',
    client_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建幂等请求标识',
    request_hash BINARY(32) NOT NULL COMMENT '初次规范请求摘要，编辑时保持',
    first_published_at DATETIME(3) NULL COMMENT '首次发布UTC时间',
    last_published_at DATETIME(3) NULL COMMENT '最近发布UTC时间',
    withdrawn_at DATETIME(3) NULL COMMENT '撤回UTC时间',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    deleted_at DATETIME(3) NULL DEFAULT NULL COMMENT '软删除UTC时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_announcement_request (created_by, client_request_id),
    KEY idx_announcement_public (status, deleted_at, scope, last_published_at, id),
    KEY idx_announcement_admin (status, category, updated_at, id),
    KEY idx_announcement_updater (updated_by),
    CONSTRAINT ck_announcement_text CHECK (CHAR_LENGTH(TRIM(title)) > 0 AND CHAR_LENGTH(TRIM(body)) > 0),
    CONSTRAINT ck_announcement_category CHECK (category IN ('community', 'activity', 'safety', 'market')),
    CONSTRAINT ck_announcement_scope CHECK (scope IN ('all', 'forum', 'market')),
    CONSTRAINT ck_announcement_status CHECK (status IN ('draft', 'published', 'withdrawn')),
    CONSTRAINT ck_announcement_request CHECK (CHAR_LENGTH(client_request_id) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='社区公告，删除与撤回分开';

CREATE TABLE xl_notification_task (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '站内通知任务主键',
    title VARCHAR(50) NOT NULL COMMENT '通知标题',
    body VARCHAR(500) NOT NULL COMMENT '完整通知正文',
    audience VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '受众口径',
    status VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'draft' COMMENT '草稿或已发送',
    created_by BIGINT UNSIGNED NOT NULL COMMENT '创建管理员',
    updated_by BIGINT UNSIGNED NOT NULL COMMENT '更新管理员',
    client_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建幂等请求标识',
    request_hash BINARY(32) NOT NULL COMMENT '初次规范请求摘要',
    sent_at DATETIME(3) NULL COMMENT '接收记录提交UTC时间',
    recipient_count INT UNSIGNED NULL COMMENT '实际去重接收人数',
    audience_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '发送时受众指纹',
    send_operation_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '发送唯一操作标识',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (id),
    UNIQUE KEY uk_task_request (created_by, client_request_id),
    UNIQUE KEY uk_task_send (send_operation_id),
    KEY idx_task_list (status, audience, updated_at, id),
    KEY idx_task_updater (updated_by),
    CONSTRAINT ck_task_text CHECK (CHAR_LENGTH(TRIM(title)) > 0 AND CHAR_LENGTH(TRIM(body)) > 0),
    CONSTRAINT ck_task_audience CHECK (audience IN ('all', 'active', 'recent', 'sellers')),
    CONSTRAINT ck_task_status CHECK (status IN ('draft', 'sent')),
    CONSTRAINT ck_task_request CHECK (CHAR_LENGTH(client_request_id) > 0),
    CONSTRAINT ck_task_count CHECK (recipient_count IS NULL OR recipient_count BETWEEN 1 AND 5000),
    CONSTRAINT ck_task_sent CHECK (status <> 'sent' OR (sent_at IS NOT NULL AND recipient_count IS NOT NULL AND audience_fingerprint IS NOT NULL AND send_operation_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='管理员站内通知任务，发送后业务只读';

CREATE TABLE xl_user_notification (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '接收通知主键',
    recipient_id BIGINT UNSIGNED NOT NULL COMMENT '实际接收用户',
    event_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '接收者内自然事件去重键',
    type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '通知展示分类',
    event_kind VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '实际事件种类',
    actor_id BIGINT UNSIGNED NULL COMMENT '触发用户，平台通知为空',
    task_id BIGINT UNSIGNED NULL COMMENT '系统通知任务',
    announcement_id BIGINT UNSIGNED NULL COMMENT '关联公告',
    target_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '可选多态目标类型',
    target_id BIGINT UNSIGNED NULL COMMENT '可选多态目标标识',
    title VARCHAR(60) NOT NULL DEFAULT '' COMMENT '安全展示标题',
    summary VARCHAR(200) NOT NULL DEFAULT '' COMMENT '安全摘要，不复制通知全文',
    read_at DATETIME(3) NULL COMMENT '已读UTC时间',
    active BOOLEAN NOT NULL DEFAULT TRUE COMMENT '事件是否有效',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (id),
    UNIQUE KEY uk_notice_event (recipient_id, event_key),
    KEY idx_notice_inbox (recipient_id, active, created_at, id),
    KEY idx_notice_unread (recipient_id, active, read_at, type, id),
    KEY idx_notice_task (task_id, recipient_id),
    KEY idx_notice_actor (actor_id),
    KEY idx_notice_announcement (announcement_id),
    CONSTRAINT ck_notice_event CHECK (CHAR_LENGTH(event_key) > 0),
    CONSTRAINT ck_notice_type CHECK (type IN ('comment', 'reaction', 'announcement')),
    CONSTRAINT ck_notice_kind CHECK (event_kind IN ('comment', 'reply', 'post_like', 'comment_like', 'post_favorite', 'product_favorite', 'system', 'announcement', 'moderation_warning')),
    CONSTRAINT ck_notice_target CHECK ((target_type IS NULL AND target_id IS NULL) OR (target_type IS NOT NULL AND target_type IN ('post', 'comment', 'product', 'user', 'message', 'announcement') AND target_id IS NOT NULL AND target_id > 0)),
    CONSTRAINT ck_notice_active CHECK (active IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='真实站内接收记录，不代表外部推送或送达';

-- 运行账号对此表仅授予SELECT和INSERT；权限由独立部署流程配置。
CREATE TABLE xl_audit_log (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '安全审计主键',
    operation_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '唯一操作诊断标识',
    actor_type VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '管理员或系统主体',
    admin_id BIGINT UNSIGNED NULL COMMENT '可选管理员内部引用',
    actor_display VARCHAR(64) NOT NULL COMMENT '安全展示名快照',
    module VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '操作业务模块',
    action VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '操作动作编码',
    target_type VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '受控目标类型',
    target_internal_id BIGINT UNSIGNED NULL COMMENT '内部追溯标识，标准DTO不返回',
    target_count INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '实际目标数量',
    outcome VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '成功、业务拒绝或执行异常',
    summary_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '安全摘要编码',
    result_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结果编码，不存原始异常',
    changed_fields JSON NOT NULL COMMENT '已提交变更字段名数组，可为空',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '追加UTC时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_audit_operation (operation_id),
    KEY idx_audit_time (created_at, id),
    KEY idx_audit_actor (admin_id, created_at, id),
    KEY idx_audit_module (module, action, outcome, created_at, id),
    CONSTRAINT ck_audit_actor CHECK (actor_type IN ('admin', 'system')),
    CONSTRAINT ck_audit_module CHECK (module IN ('posts', 'comments', 'products', 'reports', 'users', 'announcements', 'notifications', 'settings')),
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('success', 'business_rejected', 'execution_error')),
    CONSTRAINT ck_audit_fields CHECK (JSON_TYPE(changed_fields) = 'ARRAY'),
    CONSTRAINT ck_audit_codes CHECK (CHAR_LENGTH(operation_id) > 0 AND CHAR_LENGTH(action) > 0 AND CHAR_LENGTH(target_type) > 0 AND CHAR_LENGTH(summary_code) > 0 AND CHAR_LENGTH(result_code) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='独立失败隔离的安全审计，只追加';

CREATE TABLE xl_system_setting (
    setting_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '版本化配置键',
    value_json JSON NOT NULL COMMENT '受DTO限制的配置对象',
    effect_mode VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'configuration_only' COMMENT '仅配置展示模式',
    updated_by BIGINT UNSIGNED NULL COMMENT '更新管理员，默认配置可为空',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (setting_key),
    KEY idx_setting_updater (updated_by),
    CONSTRAINT ck_setting_key CHECK (setting_key = 'content_review'),
    CONSTRAINT ck_setting_value CHECK (JSON_TYPE(value_json) = 'OBJECT'),
    CONSTRAINT ck_setting_effect CHECK (effect_mode = 'configuration_only')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='版本化内容审核配置，不自动执行审核';

CREATE TABLE xl_image_asset (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '图片资源主键',
    owner_user_id BIGINT UNSIGNED NOT NULL COMMENT '资源归属用户',
    purpose VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '资源用途',
    storage_key VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL COMMENT '大小写敏感的不透明存储键',
    media_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '验证后的媒体类型',
    byte_size INT UNSIGNED NOT NULL COMMENT '安全图片字节数',
    width INT UNSIGNED NOT NULL COMMENT '安全图片像素宽度',
    height INT UNSIGNED NOT NULL COMMENT '安全图片像素高度',
    sha256 BINARY(32) NOT NULL COMMENT '资源内容摘要，不跨用户去重',
    state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'temporary' COMMENT '资源生命周期状态',
    expires_at DATETIME(3) NULL COMMENT '临时资源到期UTC时间',
    deleted_at DATETIME(3) NULL DEFAULT NULL COMMENT '资源删除UTC时间',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    PRIMARY KEY (id),
    UNIQUE KEY uk_asset_key (storage_key),
    KEY idx_asset_owner (owner_user_id, purpose, created_at, id),
    KEY idx_asset_cleanup (state, expires_at, id),
    CONSTRAINT ck_asset_purpose CHECK (purpose IN ('avatar', 'post', 'product', 'report')),
    CONSTRAINT ck_asset_dimensions CHECK (byte_size BETWEEN 1 AND 10485760 AND width > 0 AND height > 0),
    CONSTRAINT ck_asset_media_type CHECK (CHAR_LENGTH(media_type) > 0),
    CONSTRAINT ck_asset_state CHECK (state IN ('temporary', 'ready', 'deleting', 'deleted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='图片元信息，访问地址按权限临时生成';

CREATE TABLE xl_media_ref (
    owner_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '头像、内容或举报证据的拥有者类型',
    owner_id BIGINT UNSIGNED NOT NULL COMMENT '多态拥有者标识',
    position TINYINT UNSIGNED NOT NULL COMMENT '零起始展示位置',
    image_id BIGINT UNSIGNED NOT NULL COMMENT '被引用图片资源',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '引用UTC时间',
    PRIMARY KEY (owner_type, owner_id, position),
    UNIQUE KEY uk_media_owner_image (owner_type, owner_id, image_id),
    KEY idx_media_asset (image_id),
    CONSTRAINT ck_media_owner CHECK (owner_type IN ('user_avatar', 'post', 'product', 'report_evidence', 'report_snapshot') AND owner_id > 0),
    CONSTRAINT ck_media_position CHECK (owner_type <> 'user_avatar' OR position = 0),
    CONSTRAINT ck_media_evidence_count CHECK (owner_type <> 'report_evidence' OR position < 3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='图片引用，举报快照可由服务端授权保全';

CREATE TABLE xl_user_activity_day (
    user_id BIGINT UNSIGNED NOT NULL COMMENT '有效访问用户',
    activity_date DATE NOT NULL COMMENT '上海时区业务日期',
    first_seen_at DATETIME(3) NOT NULL COMMENT '该业务日首次访问UTC时间',
    last_seen_at DATETIME(3) NOT NULL COMMENT '该业务日最近访问UTC时间',
    PRIMARY KEY (user_id, activity_date),
    KEY idx_activity_day (activity_date, user_id),
    CONSTRAINT ck_activity_time CHECK (first_seen_at <= last_seen_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='成功鉴权业务访问的日活去重，可暂不开采集';
