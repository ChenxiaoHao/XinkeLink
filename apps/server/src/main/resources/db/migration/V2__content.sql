-- 内容与互动；多态目标、评论同根和可见性由服务事务校验。
CREATE TABLE xl_post (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '帖子主键',
    author_id BIGINT UNSIGNED NOT NULL COMMENT '真实作者，仅授权投影公开',
    category VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '帖子分类',
    content VARCHAR(2000) NOT NULL COMMENT '纯文本正文',
    is_anonymous BOOLEAN NOT NULL DEFAULT FALSE COMMENT '是否匿名展示',
    anonymous_label VARCHAR(24) NULL COMMENT '按帖子生成的匿名称呼',
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'visible' COMMENT '治理可见状态',
    review_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'normal' COMMENT '审核状态',
    client_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建幂等请求标识',
    request_hash BINARY(32) NOT NULL COMMENT '初次规范请求摘要，编辑时保持',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    deleted_at DATETIME(3) NULL DEFAULT NULL COMMENT '软删除UTC时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_post_request (author_id, client_request_id),
    KEY idx_post_feed (deleted_at, status, review_state, created_at, id),
    KEY idx_post_category (category, deleted_at, status, created_at, id),
    KEY idx_post_author (author_id, deleted_at, created_at, id),
    CONSTRAINT ck_post_category CHECK (category IN ('campus', 'lost_found', 'study', 'help')),
    CONSTRAINT ck_post_content CHECK (CHAR_LENGTH(TRIM(content)) > 0),
    CONSTRAINT ck_post_anonymous CHECK (is_anonymous IN (0, 1) AND (is_anonymous = 0 OR (anonymous_label IS NOT NULL AND CHAR_LENGTH(TRIM(anonymous_label)) > 0))),
    CONSTRAINT ck_post_status CHECK (status IN ('visible', 'hidden')),
    CONSTRAINT ck_post_review CHECK (review_state IN ('normal', 'pending')),
    CONSTRAINT ck_post_request CHECK (CHAR_LENGTH(client_request_id) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='论坛帖子与匿名、治理状态';

CREATE TABLE xl_comment (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '评论主键',
    target_type VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '帖子或商品目标类型',
    target_id BIGINT UNSIGNED NOT NULL COMMENT '多态目标标识',
    author_id BIGINT UNSIGNED NOT NULL COMMENT '真实作者用户',
    root_id BIGINT UNSIGNED NULL COMMENT '所属一级评论',
    reply_to_id BIGINT UNSIGNED NULL COMMENT '直接回复评论',
    content VARCHAR(1000) NOT NULL COMMENT '评论纯文本',
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'visible' COMMENT '本条可见状态',
    client_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建幂等请求标识',
    request_hash BINARY(32) NOT NULL COMMENT '初次规范请求摘要',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    deleted_at DATETIME(3) NULL DEFAULT NULL COMMENT '软删除UTC时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_comment_request (author_id, client_request_id),
    KEY idx_comment_target (target_type, target_id, deleted_at, status, root_id, created_at, id),
    KEY idx_comment_root (root_id, deleted_at, status, created_at, id),
    KEY idx_comment_author (author_id, deleted_at, created_at, id),
    KEY idx_comment_reply (reply_to_id),
    CONSTRAINT ck_comment_target CHECK (target_type IN ('post', 'product') AND target_id > 0),
    CONSTRAINT ck_comment_level CHECK ((root_id IS NULL AND reply_to_id IS NULL) OR (root_id IS NOT NULL AND reply_to_id IS NOT NULL)),
    CONSTRAINT ck_comment_content CHECK (CHAR_LENGTH(TRIM(content)) > 0),
    CONSTRAINT ck_comment_status CHECK (status IN ('visible', 'hidden')),
    CONSTRAINT ck_comment_request CHECK (CHAR_LENGTH(client_request_id) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='两级评论，跨目标和根层级由事务验证';

CREATE TABLE xl_like (
    user_id BIGINT UNSIGNED NOT NULL COMMENT '点赞用户',
    target_type VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '点赞目标类型',
    target_id BIGINT UNSIGNED NOT NULL COMMENT '多态目标标识',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '点赞UTC时间',
    PRIMARY KEY (user_id, target_type, target_id),
    KEY idx_like_target (target_type, target_id, user_id),
    KEY idx_like_user_time (user_id, created_at, target_id),
    CONSTRAINT ck_like_target CHECK (target_type IN ('post', 'comment') AND target_id > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='点赞关系，取消时物理删行';

CREATE TABLE xl_favorite (
    user_id BIGINT UNSIGNED NOT NULL COMMENT '收藏用户',
    target_type VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '收藏目标类型',
    target_id BIGINT UNSIGNED NOT NULL COMMENT '多态目标标识',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '收藏UTC时间',
    PRIMARY KEY (user_id, target_type, target_id),
    KEY idx_favorite_target (target_type, target_id, user_id),
    KEY idx_favorite_user_time (user_id, created_at, target_id),
    CONSTRAINT ck_favorite_target CHECK (target_type IN ('post', 'product') AND target_id > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='收藏关系，取消时物理删行';

CREATE TABLE xl_product (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '商品主键',
    seller_id BIGINT UNSIGNED NOT NULL COMMENT '卖家用户',
    title VARCHAR(60) NOT NULL COMMENT '商品标题',
    description VARCHAR(1000) NOT NULL COMMENT '商品描述',
    category VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '商品分类',
    price_fen INT UNSIGNED NOT NULL COMMENT '价格，单位分',
    condition_score TINYINT UNSIGNED NOT NULL COMMENT '成色编码',
    negotiable BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否可议价',
    sale_status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'available' COMMENT '在售、下架或已售',
    review_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'normal' COMMENT '审核状态',
    moderation_hidden BOOLEAN NOT NULL DEFAULT FALSE COMMENT '独立治理隐藏标记',
    client_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '创建幂等请求标识',
    request_hash BINARY(32) NOT NULL COMMENT '初次规范请求摘要，编辑时保持',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC时间',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '更新UTC时间',
    version INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
    deleted_at DATETIME(3) NULL DEFAULT NULL COMMENT '软删除UTC时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_product_request (seller_id, client_request_id),
    KEY idx_product_public (deleted_at, moderation_hidden, review_state, sale_status, created_at, id),
    KEY idx_product_category (category, deleted_at, created_at, id),
    KEY idx_product_price (deleted_at, price_fen, id),
    KEY idx_product_seller (seller_id, deleted_at, sale_status, created_at, id),
    CONSTRAINT ck_product_text CHECK (CHAR_LENGTH(TRIM(title)) > 0 AND CHAR_LENGTH(TRIM(description)) > 0),
    CONSTRAINT ck_product_category CHECK (category IN ('digital', 'books', 'living', 'fashion', 'other')),
    CONSTRAINT ck_product_price CHECK (price_fen BETWEEN 1 AND 9999999),
    CONSTRAINT ck_product_condition CHECK (condition_score IN (100, 99, 95, 90, 80)),
    CONSTRAINT ck_product_flags CHECK (negotiable IN (0, 1) AND moderation_hidden IN (0, 1)),
    CONSTRAINT ck_product_sale CHECK (sale_status IN ('available', 'off_shelf', 'sold')),
    CONSTRAINT ck_product_review CHECK (review_state IN ('normal', 'pending')),
    CONSTRAINT ck_product_request CHECK (CHAR_LENGTH(client_request_id) > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='二手商品，交易与治理状态独立';
