import { expect, test, type Page } from './api-fixture'
import fs from 'node:fs'
import path from 'node:path'

const screenshotDir = path.resolve('../../.local/admin-phase2')

async function enterDemo(page: Page, pathName: string) {
  await page.goto(pathName)
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('管理员账号').fill('demo-admin')
  await page.getByLabel('管理员密码').fill('demo-password')
  await page.getByRole('button', { name: /进入管理后台/ }).click()
  await expect(page).toHaveURL(new RegExp(`${pathName.replaceAll('/', '\\/')}$`))
  await expect(page.locator('.el-message')).toBeVisible()
  await expect(page.locator('.el-message')).toHaveCount(0)
}

async function selectTableRow(page: Page, tableTestId: string, rowIndex = 0) {
  await page.getByTestId(tableTestId).locator('.el-table__body-wrapper tbody tr').nth(rowIndex).locator('.el-checkbox__input').click()
}

async function waitForTableReady(page: Page) {
  await expect(page.locator('.el-loading-mask')).toHaveCount(0)
}

test('post management filters, paginates, opens details, moderates, deletes and batches records', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1366, height: 900 })
  await enterDemo(page, '/admin/posts')
  fs.mkdirSync(screenshotDir, { recursive: true })
  await expect(page.getByTestId('posts-view')).toBeVisible()
  await expect(page.getByRole('heading', { name: '帖子综合管理' })).toBeVisible()
  await expect(page.locator('.post-table .el-table__body-wrapper tbody tr')).toHaveCount(10)
  await waitForTableReady(page)
  await page.screenshot({ path: path.join(screenshotDir, 'posts-1366.png'), fullPage: false, animations: 'disabled' })

  const search = page.getByRole('textbox', { name: '搜索帖子' })
  await search.fill('图书馆')
  await expect(page.locator('.post-table .el-table__body-wrapper tbody tr').first()).toContainText('图书馆')
  await page.getByTestId('post-category-filter').click()
  await page.getByRole('option', { name: '学习交流' }).click()
  await page.getByTestId('post-status-filter').click()
  await page.getByRole('option', { name: '正常展示' }).click()
  await page.getByTestId('post-period-filter').click()
  await page.getByRole('option', { name: '近 30 天' }).click()
  await expect(page.locator('.post-table .el-table__body-wrapper tbody tr').first()).toContainText('图书馆')
  await waitForTableReady(page)
  await page.screenshot({ path: path.join(screenshotDir, 'posts-filtered-1366.png'), fullPage: false, animations: 'disabled' })

  await page.getByTestId('open-post-detail').first().click()
  await expect(page.getByTestId('post-detail-drawer')).toBeVisible()
  await expect(page.getByRole('heading', { name: '帖子详情' })).toBeVisible()
  await expect(page.getByText('评论与回复')).toBeVisible()
  await expect(page.getByText('回复', { exact: false }).first()).toBeVisible()
  await page.screenshot({ path: path.join(screenshotDir, 'post-detail-1366.png'), fullPage: false, animations: 'disabled' })
  await page.getByTestId('detail-hide-post').click()
  await expect(page.getByTestId('detail-restore-post')).toBeVisible()
  await expect(page.getByText('已隐藏', { exact: true }).first()).toBeVisible()
  await page.getByTestId('detail-restore-post').click()
  await expect(page.getByTestId('detail-hide-post')).toBeVisible()
  await page.getByRole('button', { name: '关闭帖子详情' }).click()
  await expect(page.getByTestId('post-detail-drawer')).toBeHidden()

  await search.fill('在教学楼 C 栋')
  await page.getByTestId('post-category-filter').click()
  await page.getByRole('option', { name: '全部分类' }).click()
  await expect(page.locator('.post-table .el-table__body-wrapper tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '删除帖子' }).click()
  await expect(page.locator('.el-message-box')).toBeVisible()
  await page.getByRole('button', { name: '确认删除' }).click()
  await expect(page.getByText('暂无符合条件的帖子')).toBeVisible()

  await search.fill('')
  await page.getByTestId('post-category-filter').click()
  await page.getByRole('option', { name: '全部分类' }).click()
  await page.getByTestId('post-status-filter').click()
  await page.getByRole('option', { name: '全部状态' }).click()
  await page.getByTestId('post-period-filter').click()
  await page.getByRole('option', { name: '全部时间' }).click()
  await selectTableRow(page, 'posts-view', 0)
  await selectTableRow(page, 'posts-view', 1)
  await expect(page.getByTestId('post-bulk-toolbar')).toBeVisible()
  await page.getByTestId('bulk-hide-posts').click()
  await expect(page.getByText('已隐藏 2 篇帖子')).toBeVisible()
  await page.getByTestId('post-status-filter').click()
  await page.getByRole('option', { name: '已隐藏' }).click()
  await expect(page.locator('.post-table .el-table__body-wrapper tbody tr').first()).toBeVisible()
  await selectTableRow(page, 'posts-view', 0)
  await page.getByTestId('bulk-restore-posts').click()
  await expect(page.getByText('已恢复 1 篇帖子')).toBeVisible()

  await page.getByTestId('post-status-filter').click()
  await page.getByRole('option', { name: '全部状态' }).click()
  await page.getByRole('button', { name: '下一页' }).click()
  await expect(page.locator('.post-table .el-table__body-wrapper tbody tr')).toHaveCount(1)
  await expect(page.getByTestId('post-pagination')).toBeVisible()

  await page.getByRole('button', { name: '上一页' }).click()
  const main = page.locator('.main-scroll')
  const topbar = page.locator('.admin-topbar')
  const sidebar = page.locator('.admin-sidebar')
  const topBefore = (await topbar.boundingBox())?.y
  const sideBefore = (await sidebar.boundingBox())?.y
  expect(await main.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await main.evaluate(element => { element.scrollTop = 450 })
  expect(await page.evaluate(() => document.documentElement.scrollTop)).toBe(0)
  expect((await topbar.boundingBox())?.y).toBe(topBefore)
  expect((await sidebar.boundingBox())?.y).toBe(sideBefore)
  expect(errors).toEqual([])
})

