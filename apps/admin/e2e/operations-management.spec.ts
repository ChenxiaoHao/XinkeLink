import { expect, test, type Page } from './api-fixture'
import fs from 'node:fs'
import path from 'node:path'

const screenshotDir = path.resolve('../../.local/admin-phase5')

async function enterDemo(page: Page, route: string) {
  await page.goto(route)
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('管理员账号').fill('demo-admin')
  await page.getByLabel('管理员密码').fill('demo-password')
  await page.getByRole('button', { name: /进入管理后台/ }).click()
  await expect(page).toHaveURL(new RegExp(`${route.replaceAll('/', '\\/')}$`))
  await expect(page.locator('.el-message')).toContainText('登录成功')
  await expect(page.locator('.el-message')).toHaveCount(0)
}

async function waitForTable(page: Page) { await expect(page.locator('.el-loading-mask')).toHaveCount(0) }

test('announcement lifecycle, filters, preview, confirmations, and fixed layout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1366, height: 760 })
  await enterDemo(page, '/admin/announcements')
  fs.mkdirSync(screenshotDir, { recursive: true })
  await expect(page.getByTestId('announcements-view')).toBeVisible()
  await expect(page.locator('.announcement-table .el-table__body-wrapper tbody tr')).toHaveCount(8)
  await waitForTable(page)
  await page.screenshot({ path: path.join(screenshotDir, 'announcements-list-1366.png'), animations: 'disabled' })

  const sidebarY = (await page.locator('.admin-sidebar').boundingBox())?.y
  const topbarY = (await page.locator('.admin-topbar').boundingBox())?.y
  const main = page.locator('.main-scroll')
  expect(await main.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await main.evaluate(element => { element.scrollTop = 350 })
  expect(await page.evaluate(() => document.documentElement.scrollTop)).toBe(0)
  expect((await page.locator('.admin-sidebar').boundingBox())?.y).toBe(sidebarY)
  expect((await page.locator('.admin-topbar').boundingBox())?.y).toBe(topbarY)
  await main.evaluate(element => { element.scrollTop = 0 })

  await page.getByRole('textbox', { name: '搜索公告' }).fill('期末')
  await page.getByTestId('announcement-category-filter').click()
  await page.getByRole('option', { name: '社区动态' }).click()
  await page.getByTestId('announcement-status-filter').click()
  await page.getByRole('option', { name: '已发布' }).click()
  await expect(page.locator('.announcement-table .el-table__body-wrapper tbody tr')).toHaveCount(1)
  await expect(page.locator('.announcement-table')).toContainText('图书馆')
  await page.getByRole('textbox', { name: '搜索公告' }).fill('')
  await page.getByTestId('announcement-category-filter').click()
  await page.getByRole('option', { name: '全部分类' }).click()
  await page.getByTestId('announcement-status-filter').click()
  await page.getByRole('option', { name: '全部状态' }).click()

  const title = 'Playwright 公告验收 - 校园生活'
  await page.getByTestId('create-announcement').click()
  await page.getByTestId('announcement-title').fill(title)
  await page.getByTestId('announcement-body').fill('这是用于浏览器验收的社区公告内容，不代表学校官方通知。')
  await page.getByTestId('announcement-category').click()
  await page.getByRole('option', { name: '活动信息' }).click()
  await page.getByTestId('announcement-scope').click()
  await page.getByRole('option', { name: '论坛', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByTestId('save-announcement-draft').click()
  await expect(page.locator('.el-message')).toHaveCount(0)
  await expect(page.locator('.announcement-table')).toContainText(title)

  let row = page.locator('.announcement-table .el-table__body-wrapper tbody tr').filter({ hasText: title })
  await row.getByTestId('announcement-edit').click()
  await page.screenshot({ path: path.join(screenshotDir, 'announcement-edit-1440.png'), animations: 'disabled' })
  await page.getByTestId('announcement-title').fill(`${title}（已更新）`)
  await page.getByTestId('save-announcement-draft').click()
  const updatedTitle = `${title}（已更新）`
  row = page.locator('.announcement-table .el-table__body-wrapper tbody tr').filter({ hasText: updatedTitle })
  await row.getByTestId('announcement-preview-action').click()
  await expect(page.getByTestId('announcement-preview-dialog')).toContainText('本地预览')
  await page.getByTestId('close-announcement-preview').click()
  await row.getByTestId('announcement-publish').click()
  let dialog = page.getByRole('dialog', { name: '发布公告前请确认' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '确认发布' }).click()
  await expect(row).toContainText('已发布')

  await row.getByTestId('announcement-withdraw').click()
  dialog = page.getByRole('dialog', { name: '确认撤回公告' })
  await dialog.getByRole('button', { name: '确认撤回' }).click()
  await expect(row).toContainText('已撤回')
  await row.getByTestId('announcement-publish').click()
  dialog = page.getByRole('dialog', { name: '发布公告前请确认' })
  await dialog.getByRole('button', { name: '确认发布' }).click()
  await expect(row).toContainText('已发布')
  await row.getByTestId('announcement-delete').click()
  dialog = page.getByRole('dialog', { name: '确认删除公告' })
  await dialog.getByRole('button', { name: '确认删除' }).click()
  await expect(page.locator('.announcement-table')).not.toContainText(updatedTitle)
  expect(errors).toEqual([])
})

test('notification audience matching, draft save, one-time simulated send, and 1440px drawer', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 900 })
  await enterDemo(page, '/admin/notifications')
  fs.mkdirSync(screenshotDir, { recursive: true })
  await expect(page.getByTestId('notifications-view')).toBeVisible()
  await expect(page.locator('.notification-table .el-table__body-wrapper tbody tr')).toHaveCount(8)
  await waitForTable(page)
  await page.screenshot({ path: path.join(screenshotDir, 'notifications-list-1440.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 1366, height: 600 })
  const listMain = page.locator('.main-scroll')
  const listSidebarY = (await page.locator('.admin-sidebar').boundingBox())?.y
  const listTopbarY = (await page.locator('.admin-topbar').boundingBox())?.y
  expect(await listMain.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await listMain.evaluate(element => { element.scrollTop = 300 })
  expect(await page.evaluate(() => document.documentElement.scrollTop)).toBe(0)
  expect((await page.locator('.admin-sidebar').boundingBox())?.y).toBe(listSidebarY)
  expect((await page.locator('.admin-topbar').boundingBox())?.y).toBe(listTopbarY)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByTestId('notification-audience-filter').click()
  await page.getByRole('option', { name: '正常状态用户' }).click()
  const activeRows = await page.locator('.notification-table .el-table__body-wrapper tbody tr').allTextContents()
  expect(activeRows.length).toBeGreaterThan(0)
  expect(activeRows.every(text => text.includes('正常状态用户'))).toBe(true)
  await page.getByTestId('notification-status-filter').click()
  await page.getByRole('option', { name: '草稿', exact: true }).click()
  const draftRows = await page.locator('.notification-table .el-table__body-wrapper tbody tr').allTextContents()
  expect(draftRows.length).toBeGreaterThan(0)
  expect(draftRows.every(text => text.includes('草稿'))).toBe(true)
  await page.getByTestId('notification-audience-filter').click()
  await page.getByRole('option', { name: '全部接收范围' }).click()
  await page.getByTestId('notification-status-filter').click()
  await page.getByRole('option', { name: '全部状态' }).click()

  const title = 'Playwright 通知验收 - 活跃用户'
  await page.getByTestId('create-notification').click()
  await page.getByTestId('notification-title').fill(title)
  await page.getByTestId('notification-body').fill('请关注信科 Link 校园社区内的最新交流内容。')
  await page.getByTestId('notification-audience').click()
  await page.getByRole('option', { name: '近 30 天活跃用户' }).click()
  const count = Number((await page.getByTestId('audience-match-count').innerText()).match(/\d+/)?.[0] ?? 0)
  expect(count).toBeGreaterThan(0)
  await expect(page.getByTestId('notification-editor-drawer')).toContainText('不发送微信订阅消息')
  await page.screenshot({ path: path.join(screenshotDir, 'notification-create-drawer-1440.png'), animations: 'disabled' })
  await page.getByTestId('save-notification-draft').click()

  await page.getByRole('textbox', { name: '搜索通知' }).fill(title)
  await expect(page.locator('.notification-table .el-table__body-wrapper tbody tr')).toHaveCount(1)
  const row = page.locator('.notification-table .el-table__body-wrapper tbody tr').filter({ hasText: title })
  await row.getByTestId('notification-send-row').click()
  await expect(page.getByTestId('audience-match-count')).toContainText(String(count))
  await page.getByTestId('confirm-notification-send').click()
  const dialog = page.getByRole('dialog', { name: '发送前风险提示' })
  await expect(dialog).toContainText('真实站内通知')
  await dialog.getByRole('button', { name: '确认发送站内通知' }).click()
  await expect(row).toContainText('已发送站内通知')
  await expect(row.getByTestId('notification-send-row')).toHaveCount(0)
  await row.getByTestId('notification-view-action').click()
  await expect(page.getByTestId('notification-send-record')).toContainText('站内发送')
  await expect(page.getByTestId('notification-send-record')).toContainText('未发送')
  await expect(page.getByTestId('notification-editor-drawer')).toContainText(`${count}位用户`)
  expect(errors).toEqual([])
})
